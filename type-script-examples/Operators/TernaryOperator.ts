/**
 * Ternary Operator or candiditional operator ?:
 * The ternary operator is a shorthand way of writing an if-else statement. It takes three operands: a condition, a value to return if the condition is true, and a value to return if the condition is false.
 * 
 * Syntax: let result : datatype = condition ? value_if_true : value_if_false
 * 
 */
 
let age: number = 18;
let isAdult: string = (age >= 18) ? "Yes, is an adult." : "No, is not an adult.";
console.log("Is the person an adult? :", isAdult); // Output: Yes, is an adult. 
 